# Day 2 - Variables and Data Types in Python

# Variables
name = "Sreepathi Lalitendra"
age = 18

print(name)
print(age)


# Creating variables
name = "Sreepathi Lalitendra"
age = 18
course = "Diploma CSE"

print(name)
print(age)
print(course)


# Changing the value of a variable
age = 18
print(age)

age = 19
print(age)


# Multiple variables
name = "Sreepathi Lalitendra"
age = 18
city = "Hyderabad"
course = "Diploma CSE"

print(name)
print(age)
print(city)
print(course)


# Multiple assignment
name, age, city, course = "Sreepathi Lalitendra", 18, "Hyderabad", "Diploma CSE"

print(name)
print(age)
print(city)
print(course)


# Data Types in Python

# String
name = "Sreepathi Lalitendra"
language = "Python"

print(name)
print(language)


# Integer
age = 18
marks = 85
year = 2026

print(age)
print(marks)
print(year)


# Float
height = 5.8
percentage = 85.5
price = 99.99

print(height)
print(percentage)
print(price)


# Boolean
is_student = True
is_working = False

print(is_student)
print(is_working)


# Checking data types
name = "Sreepathi Lalitendra"
age = 18
percentage = 85.5
is_student = True

print(type(name))
print(type(age))
print(type(percentage))
print(type(is_student))